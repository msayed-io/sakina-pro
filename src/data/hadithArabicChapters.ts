/** اسم الباب العربي من عنوانه الإنجليزي، أو null. */
export function arabicChapterFor(bookId: string, englishTitle: string): string | null {
  const key = normalizeChapterTitle(englishTitle);
  if (!key) return null;
  return ARABIC_CHAPTER_BY_BOOK[bookId + "::" + key] ?? ARABIC_CHAPTER_GLOBAL[key] ?? null;
}

/** اسم الباب العربي من رقمه داخل كتابه، أو null. */
export function arabicChapterByNumber(bookId: string, sectionNumber: string): string | null {
  const table = ARABIC_CHAPTER_BY_NUMBER[bookId];
  if (!table) return null;
  return table[String(sectionNumber ?? "").trim()] ?? null;
}

/** هل النص بديل رقمي مُخترَع (قديم) يجب استبداله؟ */
export function isPlaceholderChapterTitle(title: string): boolean {
  const value = String(title ?? "").trim();
  return value === "" || /^(كتاب|باب)\s*رقم/.test(value);
}

/** وسم تسجيل ثابت لفشل حل اسم الباب (لا يظهر للمستخدم). */
export const CHAPTER_RESOLVE_TAG = "[hadith-chapter]";

/**
 * الحل الوحيد لاسم الباب العربي — تستعمله كل الشاشات والمسارات.
 * الترتيب: رقم الباب في كتابه ← العنوان الإنجليزي ← النص العربي كما هو.
 * لا يخترع اسمًا ولا يعيد رقمًا. عند الفشل يعيد "" ويسجّل بالوسم الثابت.
 */
export function resolveChapterTitle(
  bookId: string,
  sectionNumber: string,
  rawTitle?: string,
): string {
  const raw = String(rawTitle ?? "").trim();

  // ① الاسم الأصلي بالرقم داخل الكتاب (الأدق: لا يعتمد على نص العنوان).
  const byNumber = arabicChapterByNumber(bookId, sectionNumber);
  if (byNumber) return byNumber;

  // ② الاسم الأصلي بالعنوان الإنجليزي.
  const byTitle = arabicChapterFor(bookId, raw);
  if (byTitle) return byTitle;

  // ③ عنوان عربي أصلي من المصدر نفسه يُعرض كما هو.
  if (/[\u0600-\u06FF]/.test(raw) && !isPlaceholderChapterTitle(raw)) return raw;

  console.warn(
    CHAPTER_RESOLVE_TAG,
    "لم يُحلّ اسم الباب",
    JSON.stringify({ bookId, sectionNumber, rawTitle: raw }),
  );
  return "";
}
